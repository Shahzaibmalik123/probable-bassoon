create extension if not exists pgcrypto;

create table if not exists public.files (
  id uuid primary key,
  original_name text not null,
  stored_name text not null,
  storage_path text not null unique,
  file_type text not null,
  uploaded_at timestamptz not null default now(),
  row_count integer not null default 0,
  extracted_text text not null
);

create index if not exists files_uploaded_at_idx on public.files (uploaded_at desc);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

-- This app accesses tables from its server with the service-role key only.
-- Never expose SUPABASE_SERVICE_ROLE_KEY in frontend code. RLS is enabled as a defence-in-depth measure.
alter table public.files enable row level security;
alter table public.messages enable row level security;

-- Create a PRIVATE bucket for original uploaded files. The server uses service role for storage operations.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('agent-files', 'agent-files', false, 4194304,
  array['text/csv','text/plain','text/markdown','application/json','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet','application/vnd.ms-excel','application/octet-stream'])
on conflict (id) do update set public = false, file_size_limit = 4194304;
